const drcCase = (
  id: PipelineCaseGroup["id"],
  status: PipelineCaseGroup["status"],
  name: string,
  variant: string,
  run: string,
  scene: string,
  noise: string,
  headline: string,
  note: string,
  detail: string,
  sampleRate: number,
  delaySamples: number,
  analysis: string,
  afterLabel: string,
): PipelineCaseGroup => {
  const key = caseKey(run, scene, noise);
  return {
    id,
    status,
    headline,
    note,
    caseAudio: caseAudio(name, {
      id: key,
      detail,
      sampleRate,
      windowSeconds: [13, 21],
      delaySamples,
      beforeLabel: "配对控制 · 无 TX DRC / 无 limiter",
      afterLabel,
      beforeFile: resultWav("bypass", key),
      afterFile: resultWav(variant, key),
      analysis,
    }),
  };
};

