const bfCase = (
  kind: "pass" | "fail",
  name: string,
  variant: string,
  sceneId: string,
  headline: string,
  note: string,
  detail: string,
  analysis: string,
  delaySamples: number,
  afterLabel: string,
): PipelineCaseGroup => ({
  id: kind,
  status: kind === "pass" ? "通过" : "失败",
  headline,
  note,
  caseAudio: caseAudio(name, {
    id: sceneId,
    detail,
    sampleRate: 16000,
    windowSeconds: sceneId.includes("multirender") ? [12, 15] : [13, 21],
    delaySamples,
    beforeLabel: "配对控制 · BF 关闭 / 通道 0",
    afterLabel,
    beforeFile: resultWav("no_bf", sceneId),
    afterFile: resultWav(variant, sceneId),
    analysis,
  }),
});

