@app.get("/api/synthesize/demo/{scenario}/{role}")
def synthesize_demo(scenario: str, role: str):
    if role not in ("microphone", "reference"):
        raise HTTPException(404, "示例音频角色不存在")
    try:
        microphone, reference = demo_pair(scenario)
    except AudioError as error:
        raise HTTPException(404, str(error)) from error
    payload = microphone if role == "microphone" else reference
    return Response(payload, media_type="audio/wav",
                    headers={"Content-Disposition": f'inline; filename="demo-{scenario}-{role}.wav"'})



@app.post("/api/synthesize/{result_id}/graphics")
async def synthesize_result_graphics(result_id: str):
    with _RESULTS_LOCK:
        entry = _RESULTS.get(result_id)
        if entry and time.monotonic() - entry[0] > _RESULT_TTL_SECONDS:
            _RESULTS.pop(result_id, None)
            entry = None
    if entry is None or entry[2] is None:
        raise HTTPException(404, "结果已过期，请重新生成后绘图")
    context = entry[2]

    def calculate():
        with _FIGURE_GENERATION_LOCK:
            report, figures = synthesis_graphics(context)
        return _publish_result(report, figures)

    try:
        return await run_in_threadpool(calculate)
    except (AudioError, OSError, ValueError) as error:
        raise HTTPException(422, str(error)) from error


@app.get("/api/synthesize/{result_id}")
def synthesize_download(result_id: str):
    with _RESULTS_LOCK:
        entry = _RESULTS.get(result_id)
        if entry and time.monotonic() - entry[0] > _RESULT_TTL_SECONDS:
            _RESULTS.pop(result_id, None)
            entry = None
    if not entry:
        raise HTTPException(404, "结果已过期，请重新生成")
    # `inline` so the page can play the result directly; the download button
    # uses the HTML download attribute for the saved filename.
    return Response(entry[1], media_type="audio/wav",
                    headers={"Content-Disposition": 'inline; filename="itu-processed.wav"'})
