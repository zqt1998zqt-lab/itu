from __future__ import annotations

import json
import secrets
import time
from datetime import datetime, timezone
from threading import Lock
from typing import Annotated

from fastapi import FastAPI, File, Form, HTTPException, UploadFile
from fastapi.responses import Response
from pydantic import ValidationError
from starlette.concurrency import run_in_threadpool

from server.audio import AudioError, MAX_BYTES, Options, ROLES, analyze, decode, demo_wav
from server.synthesize import SUPPORTED_RATES, synthesize

app = FastAPI(title="ITU Audio Lab", version="2.0.0")


@app.get("/api/health")
def health():
    return {"status": "ok", "engine": "itu-engineering-dsp/2.0", "formats": ["WAV", "FLAC", "MP3", "OGG", "M4A", "AAC", "AIFF"], "max_seconds": 120, "max_bytes": MAX_BYTES}


@app.get("/api/demo/{role}")
def demo(role: str):
    if role not in ROLES:
        raise HTTPException(404, "音频角色不存在")
    return Response(demo_wav(role), media_type="audio/wav", headers={"Content-Disposition": f'attachment; filename="demo-{role}.wav"'})


@app.post("/api/analyze")
async def analyze_uploads(
    after: Annotated[UploadFile, File()],
    options: Annotated[str, Form()] = "{}",
    reference: Annotated[UploadFile | None, File()] = None,
    before: Annotated[UploadFile | None, File()] = None,
    echo: Annotated[UploadFile | None, File()] = None,
):
    uploads = {k: v for k, v in {"reference": reference, "before": before, "after": after, "echo": echo}.items() if v is not None}
    try:
        config = Options.model_validate(json.loads(options))
        blobs = {}
        for role, upload in uploads.items():
            data = await upload.read(MAX_BYTES + 1)
            if len(data) > MAX_BYTES:
                raise AudioError(f"{ROLES[role]}：文件超过 32 MB")
            blobs[role] = (upload.filename or "audio.wav", data)

        def calculate():
            audios = {role: decode(role, name, blob, config.channels.get(role, 0)) for role, (name, blob) in blobs.items()}
            result = analyze(audios, config)
            result["created_at"] = datetime.now(timezone.utc).isoformat()
            return result

        return await run_in_threadpool(calculate)
    except (AudioError, ValidationError, json.JSONDecodeError) as error:
        raise HTTPException(status_code=422, detail=str(error)) from error
    finally:
        for upload in uploads.values():
            await upload.close()


# ---------------------------------------------------------------- engine output
# Processed audio is generated by the pinned CLI, not by this process, so the
# payload is handed back through a short-lived in-memory handle instead of the
# JSON response.
_RESULTS: dict[str, tuple[float, bytes]] = {}
_RESULTS_LOCK = Lock()
_RESULT_TTL_SECONDS = 1800.0
_RESULT_KEEP = 8


def _store_result(payload: bytes) -> str:
    identifier = secrets.token_urlsafe(16)
    with _RESULTS_LOCK:
        now = time.monotonic()
        for key in [k for k, (created, _) in _RESULTS.items() if now - created > _RESULT_TTL_SECONDS]:
            _RESULTS.pop(key, None)
        _RESULTS[identifier] = (now, payload)
        while len(_RESULTS) > _RESULT_KEEP:
            _RESULTS.pop(next(iter(_RESULTS)))
    return identifier


@app.post("/api/synthesize")
async def synthesize_pair(
    microphone: Annotated[UploadFile, File()],
    reference: Annotated[UploadFile, File()],
    options: Annotated[str, Form()] = "{}",
):
    uploads = {"microphone": microphone, "reference": reference}
    try:
        config = json.loads(options or "{}")
        rate = config.get("sample_rate")
        if rate is not None and int(rate) not in SUPPORTED_RATES:
            raise AudioError("采样率只能是 16000 / 24000 / 48000")
        blobs = {}
        for role, upload in uploads.items():
            data = await upload.read(MAX_BYTES + 1)
            if len(data) > MAX_BYTES:
                raise AudioError(f"{'麦克音' if role == 'microphone' else '参考音'}：文件超过 32 MB")
            blobs[role] = (upload.filename or "audio.wav", data)

        def calculate():
            result = synthesize(
                blobs["microphone"][0], blobs["microphone"][1],
                blobs["reference"][0], blobs["reference"][1],
                rate=int(rate) if rate else None,
                profile=config.get("profile"),
            )
            wav = result.pop("wav")
            result["created_at"] = datetime.now(timezone.utc).isoformat()
            result["download_url"] = f"/api/synthesize/{_store_result(wav)}"
            return result

        return await run_in_threadpool(calculate)
    except (AudioError, ValidationError, json.JSONDecodeError, TypeError, ValueError) as error:
        raise HTTPException(status_code=422, detail=str(error)) from error
    finally:
        for upload in uploads.values():
            await upload.close()


@app.get("/api/synthesize/{result_id}")
def synthesize_download(result_id: str):
    with _RESULTS_LOCK:
        entry = _RESULTS.get(result_id)
        if entry and time.monotonic() - entry[0] > _RESULT_TTL_SECONDS:
            _RESULTS.pop(result_id, None)
            entry = None
    if not entry:
        raise HTTPException(404, "结果已过期，请重新生成")
    # `inline` so the page can play the result directly; the download button
    # uses the HTML download attribute for the saved filename.
    return Response(entry[1], media_type="audio/wav",
                    headers={"Content-Disposition": 'inline; filename="itu-processed.wav"'})
